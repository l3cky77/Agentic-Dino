@app.route("/api/open-url", methods=["POST"])
def open_url():
    user, error = require_user_json()

    if error:
        return error

    payload = request.get_json(silent=True) or {}

    url = str(
        payload.get("url", "")
    ).strip()

    if not safe_http_url(url):
        return jsonify({
            "error": "Enter a valid HTTP or HTTPS URL."
        }), 400

    return jsonify({
        "success": True,
        "url": url,
        "message": (
            "URL validated. Confirm on the companion "
            "device to open it."
        ),
    })


