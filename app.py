@app.route("/api/pair-code", methods=["POST"])
def pair_code():
    user, error = require_user_json()

    if error:
        return error

    code = str(
        secrets.randbelow(900000) + 100000
    )

    expiry = (
        datetime.now(timezone.utc)
        + timedelta(minutes=5)
    )

    with db() as conn:
        conn.execute(
            """
            UPDATE pair_codes
            SET used = TRUE
            WHERE user_id = %s AND used = FALSE
            """,
            (user["id"],),
        )

        conn.execute(
            """
            INSERT INTO pair_codes (
                user_id,
                code,
                expires_at
            )
            VALUES (%s, %s, %s)
            """,
            (
                user["id"],
                code,
                expiry,
            ),
        )

    return jsonify({
        "code": code,
        "expires_in_seconds": 300,
    })


