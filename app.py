@app.route("/api/pair", methods=["POST"])
def consume_pair_code():
    payload = request.get_json(silent=True) or {}

    code = str(
        payload.get("code", "")
    ).strip()

    if not re.fullmatch(r"\d{6}", code):
        return jsonify({
            "error": "Enter a valid six-digit code."
        }), 400

    now = datetime.now(timezone.utc)

    with db() as conn:
        row = conn.execute(
            """
            SELECT id, expires_at
            FROM pair_codes
            WHERE code = %s
              AND used = FALSE
            FOR UPDATE
            """,
            (code,),
        ).fetchone()

        if not row:
            return jsonify({
                "error": "Code is invalid or already used."
            }), 400

        expires_at = row["expires_at"]

        if expires_at.tzinfo is None:
            expires_at = expires_at.replace(
                tzinfo=timezone.utc
            )

        if expires_at < now:
            conn.execute(
                """
                UPDATE pair_codes
                SET used = TRUE
                WHERE id = %s
                """,
                (row["id"],),
            )

            return jsonify({
                "error": "Code expired. Generate a new code."
            }), 400

        conn.execute(
            """
            UPDATE pair_codes
            SET used = TRUE
            WHERE id = %s
            """,
            (row["id"],),
        )

    return jsonify({
        "success": True,
        "message": (
            "Pairing code accepted. "
            "This demo confirms pairing only."
        ),
    })


