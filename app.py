def current_user():
    user_id = session.get("user_id")

    if not user_id:
        return None

    with db() as conn:
        user = conn.execute(
            """
            SELECT id, username
            FROM users
            WHERE id = %s
            """,
            (user_id,),
        ).fetchone()

    return user


def require_user_json():
    user = current_user()

    if not user:
        return None, (
            jsonify({"error": "Please sign in first."}),
            401,
        )

    return user, None


