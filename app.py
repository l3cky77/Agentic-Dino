@app.route("/api/chat", methods=["POST"])
def api_chat():
    user, error = require_user_json()

    if error:
        return error

    payload = request.get_json(silent=True) or {}

    message = str(
        payload.get("message", "")
    ).strip()

    history = payload.get("history", [])

    if not message:
        return jsonify({
            "error": "Please enter a message."
        }), 400

    if len(message) > 5000:
        return jsonify({
            "error": "Message is too long."
        }), 400

    if not isinstance(history, list):
        history = []

    answer = gemini_reply(message, history)

    try:
        with db() as conn:
            conn.execute(
                """
                INSERT INTO tasks (
                    user_id,
                    prompt,
                    status,
                    result
                )
                VALUES (%s, %s, %s, %s)
                """,
                (
                    user["id"],
                    message[:1000],
                    "completed",
                    answer[:8000],
                ),
            )

    except Exception:
        app.logger.exception(
            "Failed to save chat task to database"
        )

        return jsonify({
            "error": (
                "The response could not be saved. "
                "Please try again."
            )
        }), 500

    return jsonify({
        "reply": answer,
    })


