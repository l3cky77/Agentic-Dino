def safe_http_url(value):
    try:
        parsed = urlparse(value.strip())

        if parsed.scheme not in ("http", "https"):
            return False

        if not parsed.hostname:
            return False

        hostname = parsed.hostname.lower()

        blocked_hosts = {
            "localhost",
            "127.0.0.1",
            "0.0.0.0",
            "::1",
        }

        if hostname in blocked_hosts:
            return False

        return True

    except (ValueError, AttributeError):
        return False


